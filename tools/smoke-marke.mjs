// Headless: Sickinger-Oberfläche mit selbst erzeugtem Testteil (keine Kundendatei).
import { chromium } from 'playwright-core';
import fs from 'fs';
const port = process.env.PORT || '4174';
const ziel = process.env.SHOT || 'docs/sickinger-oberflaeche.png';
const b = await chromium.launch({ executablePath: process.env.CHROME || '/usr/bin/google-chrome', args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader'] });
const p = await b.newPage({ viewport: { width: 1500, height: 900 } });
const errs = [];
p.on('pageerror', e => errs.push(e.message));
await p.goto('http://localhost:' + port + '/');
await p.waitForFunction(() => window.__loadUrl);
const titel = await p.title();
if (titel !== 'Sickinger STEP-Viewer') throw new Error('Fenstertitel: ' + titel);
const kopf = await p.locator('header .brand').innerText();
if (!kopf.includes('SICKINGER') || !kopf.includes('STEP-Viewer')) throw new Error('Kopfzeile: ' + kopf);
const logo = await p.locator('header .brand img.logo').getAttribute('src');
if (!logo || !logo.includes('sickinger')) throw new Error('Logo fehlt in der Kopfzeile');
const farbe = await p.locator('header label.btn.primary').evaluate(el => getComputedStyle(el).backgroundColor);
if (farbe !== 'rgb(0, 158, 223)') throw new Error('Akzentfarbe: ' + farbe);
const primaer = await p.locator('header .brand').evaluate(el => getComputedStyle(el).color);
if (primaer !== 'rgb(0, 75, 133)') throw new Error('Primärfarbe: ' + primaer);
await p.evaluate(() => window.__loadUrl('./testblech.step'));
await p.waitForFunction(() => window.__lastLoad && window.__lastLoad.bodies > 0, { timeout: 60000 });
const menues = await p.locator('nav.menue').innerText();
for (const w of ['Datei', 'Ansicht', 'Werkzeuge', 'Hilfe']) if (!menues.includes(w)) throw new Error('Menü fehlt: ' + w);
const rose = await p.locator('#kompass').innerText();
for (const w of ['N', 'O', 'S', 'W']) if (!rose.includes(w)) throw new Error('Kompass fehlt: ' + w);
if ((await p.locator('body').innerText()).includes('GmbH ·')) throw new Error('Windows-Tooltip nachgebaut');
await p.waitForTimeout(600);
fs.mkdirSync('docs', { recursive: true });
await p.screenshot({ path: ziel });
await p.click('#ueber');
await p.waitForSelector('#ueberDlg:not([hidden])');
const dlg = await p.locator('#ueberDlg').innerText();
if (!dlg.includes('Sickinger STEP-Viewer') || !dlg.includes('Manfred Sickinger Apparatebau') || !dlg.includes('Entwickelt von Hasi Elektronic')) throw new Error('Über-Dialog: ' + dlg);
if (dlg.includes('STEP-Betrachter')) throw new Error('Über-Dialog nennt noch Betrachter');
await p.evaluate(() => { window.__lastSheet = null; window.__app.tab('blech'); });
await p.waitForFunction(() => window.__lastSheet && window.__lastSheet.flat, { timeout: 60000 });
await p.click('#expPdf');
await p.waitForFunction(() => window.__lastExport?.name?.endsWith('_Biegetabelle.pdf'));
const biege = await p.evaluate(() => new TextDecoder('latin1').decode(Uint8Array.from(window.__lastExport.bytes)));
if (!biege.includes('Sickinger STEP-Viewer') || !biege.includes('Entwickelt von Hasi Elektronic') || !biege.includes('Biegetabelle')) throw new Error('Biegetabelle-PDF ohne Sickinger-Kopf');
if (biege.includes('STEP-Betrachter')) throw new Error('Biegetabelle nennt noch Betrachter');
await p.evaluate(() => window.__app.exportPdf());
await p.waitForFunction(() => window.__lastExport?.name?.endsWith('_Bemaßung.pdf'));
const bem = await p.evaluate(() => new TextDecoder('latin1').decode(Uint8Array.from(window.__lastExport.bytes)));
if (!bem.includes('Sickinger STEP-Viewer') || !bem.includes('Entwickelt von Hasi Elektronic')) throw new Error('Bemaßungs-PDF ohne Sickinger-Kopf');
if (bem.includes('STEP-Betrachter')) throw new Error('Bemaßungs-PDF nennt noch Betrachter');
if (errs.length) throw new Error(errs.join(' | '));
await b.close();
console.log('OK: Sickinger-Oberfläche', ziel);
