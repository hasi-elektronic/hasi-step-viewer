// Kopfleiste, Ansichtswürfel und Tastenkürzel. Screenshot mit dem selbst erzeugten Testblech.
import { chromium } from 'playwright-core';
import fs from 'fs';
const port = process.env.PORT || '4173';
const ziel = process.env.SHOT || 'docs/hasi-oberflaeche.png';
const b = await chromium.launch({ executablePath: process.env.CHROME || '/usr/bin/google-chrome', args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader'] });
const p = await b.newPage({ viewport: { width: 1500, height: 900 } });
const errs = [];
p.on('pageerror', e => errs.push(e.message));
const fail = m => { throw new Error(m); };
await p.goto('http://localhost:' + port + '/');
await p.waitForFunction(() => window.__loadUrl);
const menues = await p.locator('nav.menue').innerText();
for (const w of ['Datei', 'Ansicht', 'Werkzeuge', 'Hilfe']) if (!menues.includes(w)) fail('Menü fehlt: ' + w);
for (const w of ['N', 'O', 'S', 'W']) if (!(await p.locator('#kompass').innerText()).includes(w)) fail('Kompass: ' + w);
if ((await p.locator('body').innerText()).includes('GmbH ·')) fail('Windows-Tooltip nachgebaut');
await p.locator('#hilfeDlg').evaluate(el => { el.hidden = false; });
const hilfe = await p.locator('#hilfeDlg').innerText();
for (const w of ['F9', 'F10', 'Strg+1', 'Strg+5', 'Einpassen']) if (!hilfe.includes(w)) fail('Hilfe ohne ' + w);
await p.locator('#hilfeZu').click();
await p.evaluate(() => window.__loadUrl('./testblech.step'));
await p.waitForFunction(() => window.__lastLoad && window.__lastLoad.bodies > 0, { timeout: 60000 });
await p.evaluate(() => window.__app.schief());
await p.waitForTimeout(50);
const vorher = await p.evaluate(() => window.__app.ausrichtung());
if (vorher.blick > 0.98 && vorher.oben > 0.98) fail('Testlage ist nicht schief');
await p.keyboard.press('F9');
await p.waitForFunction(() => window.__app.animFertig(), { timeout: 3000 });
const nachF9 = await p.evaluate(() => window.__app.ausrichtung());
if (nachF9.blick < 0.98 || nachF9.oben < 0.98) fail('F9 richtet nicht aus: ' + JSON.stringify(nachF9));
await p.keyboard.press('F10');
await p.waitForFunction(() => window.__app.animFertig(), { timeout: 3000 });
const iso = await p.evaluate(() => window.__app.ausrichtung());
const isoSoll = [0.8, 0.6, 1];
const isoL = Math.hypot(...isoSoll);
const dotIso = iso.dir.reduce((s, v, i) => s + v * isoSoll[i] / isoL, 0);
if (dotIso < 0.98) fail('F10 ohne Fläche ist nicht Iso: ' + JSON.stringify(iso));
await p.keyboard.press('Control+Digit5');
await p.waitForFunction(() => window.__app.animFertig(), { timeout: 3000 });
const oben = await p.evaluate(() => window.__app.ausrichtung());
if (oben.dir[1] < 0.98 || oben.up[2] > -0.98) fail('Strg+5 ist nicht Oben: ' + JSON.stringify(oben));
await p.keyboard.press('Digit1');
await p.waitForFunction(() => window.__app.animFertig(), { timeout: 3000 });
const vorne = await p.evaluate(() => window.__app.ausrichtung());
if (vorne.dir[2] < 0.98 || vorne.oben < 0.98) fail('Taste 1 ist nicht Vorne: ' + JSON.stringify(vorne));
await p.evaluate(async () => {
  const app = window.__app;
  app.clearSel();
  const i = app.data().uniq[0].faces.findIndex(f => f.type === 'eben');
  await app.select({ k: 'face', id: i, inst: 0 });
});
await p.keyboard.press('F10');
await p.waitForFunction(() => window.__app.animFertig(), { timeout: 3000 });
const normal = await p.evaluate(() => window.__app.ausrichtung());
if (normal.blick < 0.98) fail('F10 folgt der Fläche nicht: ' + JSON.stringify(normal));
const ring = await p.locator('#kring').boundingBox();
await p.mouse.move(ring.x + ring.width / 2, ring.y + 8);
await p.mouse.down();
await p.mouse.move(ring.x + ring.width - 10, ring.y + ring.height / 2, { steps: 6 });
await p.mouse.up();
const gedreht = await p.evaluate(() => window.__app.camPos());
if (!gedreht) fail('Kamera fehlt');
await p.click('#wuerfelHome');
await p.waitForFunction(() => window.__app.animFertig(), { timeout: 3000 });
await p.evaluate(() => window.__app.fitIso());
await p.waitForTimeout(400);
fs.mkdirSync('docs', { recursive: true });
await p.screenshot({ path: ziel });
if (errs.length) fail(errs.join(' | '));
await b.close();
console.log('OK: Oberfläche', ziel);
