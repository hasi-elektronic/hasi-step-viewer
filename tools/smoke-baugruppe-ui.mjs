// Baugruppe: Triade/Verschieben, Ein-/Ausblenden, Messen über Bauteile. Screenshot mit Testbaugruppe.
import { chromium } from 'playwright-core';
import fs from 'fs';
import assert from 'assert';
for (const d of ['public', 'dist']) if (fs.existsSync(d)) fs.copyFileSync('testdaten/testbaugruppe.step', d + '/testbaugruppe.step');
const port = process.env.PORT || '4173';
const ziel = process.env.SHOT || 'docs/hasi-baugruppe.png';
const b = await chromium.launch({ executablePath: process.env.CHROME || '/usr/bin/google-chrome', args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader'] });
const p = await b.newPage({ viewport: { width: 1500, height: 900 } });
const errs = [];
p.on('pageerror', e => errs.push(e.message));
await p.goto('http://localhost:' + port + '/');
await p.waitForFunction(() => window.__loadUrl);
await p.evaluate(() => window.__loadUrl('./testbaugruppe.step'));
await p.waitForFunction(() => window.__lastLoad && window.__lastLoad.bodies === 5, { timeout: 90000 });
const namen = await p.$$eval('#tree .nm', e => e.map(x => x.textContent));
assert.deepEqual(namen, ['Halter komplett', 'Grundplatte', 'Winkelbaugruppe', 'Winkel links', 'Winkel rechts', 'Bolzen 1 <1>', 'Bolzen 1 <2>']);
assert.ok(!namen.some(n => /open cascade/i.test(n)));
const zeile = name => p.locator('#tree .trow', { has: p.locator('.nm', { hasText: new RegExp('^' + name.replace(/[<>]/g, '.') + '$') }) }).first();
await zeile('Grundplatte').click();
assert.equal(await p.evaluate(() => window.__app.gizmo()), true);
const mitte = await p.evaluate(() => window.__app.screenOf(window.__app.triadePos()));
const tx0 = await p.evaluate(() => window.__app.matrizen()[0][3]);
await p.mouse.move(mitte[0], mitte[1]);
await p.mouse.down();
await p.mouse.move(mitte[0] + 70, mitte[1] + 24, { steps: 8 });
await p.mouse.up();
const tx1 = await p.evaluate(() => window.__app.matrizen()[0][3]);
if (Math.abs(tx1 - tx0) < 1e-4) throw new Error('Triade-Zug hat nicht verschoben');
await p.evaluate(() => window.__app.rueckgaengig());
await p.evaluate(() => window.__app.oeffneBewegen());
await p.fill('#dx', '5');
await p.fill('#dWinkel', '0');
await p.click('#bewegenAnwenden');
const tx2 = await p.evaluate(() => window.__app.matrizen()[0][3]);
if (Math.abs(tx2 - tx0 - 5) > 1e-4) throw new Error('Numerisch ΔX: ' + tx2 + ' statt ' + (tx0 + 5));
await p.evaluate(() => window.__app.resetPos('Grundplatte'));
await zeile('Winkelbaugruppe').click();
assert.equal(await p.evaluate(() => window.__app.gizmo()), true);
const vor = await p.evaluate(() => window.__app.matrizen().slice(1, 3).map(m => m[3]));
await p.evaluate(() => window.__app.verschiebe('Winkelbaugruppe', 10, 0, 0));
const nach = await p.evaluate(() => window.__app.matrizen().slice(1, 3).map(m => m[3]));
if (Math.abs(nach[0] - vor[0] - 10) > 1e-6 || Math.abs(nach[1] - vor[1] - 10) > 1e-6) throw new Error('Unterbaugruppe nicht gemeinsam verschoben ' + vor + ' -> ' + nach);
await p.evaluate(() => window.__app.rueckgaengig());
const zurueck = await p.evaluate(() => window.__app.matrizen().slice(1, 3).map(m => m[3]));
if (Math.abs(zurueck[0] - vor[0]) > 1e-6 || Math.abs(zurueck[1] - vor[1]) > 1e-6) throw new Error('Rückgängig fehlgeschlagen');
await p.evaluate(() => window.__app.wiederholen());
await p.evaluate(() => window.__app.resetPos('Winkelbaugruppe'));
const reset = await p.evaluate(() => window.__app.matrizen().slice(1, 3).map(m => m[3]));
if (Math.abs(reset[0] - vor[0]) > 1e-6) throw new Error('Position zurücksetzen fehlgeschlagen');
await zeile('Grundplatte').click({ modifiers: ['Control'] });
const markiert = await p.$$eval('#tree .trow.sel .nm', e => e.map(x => x.textContent));
if (!markiert.includes('Winkelbaugruppe') || !markiert.includes('Grundplatte')) throw new Error('Mehrfachauswahl ' + markiert.join(','));
await zeile('Bolzen 1 <2>').click();
await p.evaluate(() => window.__app.act('toggle', window.__app.nodes().find(n => n.name === 'Bolzen 1 <2>')));
assert.equal(await zeile('Bolzen 1 <2>').evaluate(el => el.classList.contains('aus')), true);
const vis = await p.evaluate(() => window.__app.vis());
assert.equal(vis[4], false);
const pt = await p.evaluate(() => window.__app.screenOf([60, -25, 12]));
await p.mouse.move(pt[0], pt[1]);
await p.keyboard.press('Shift+Tab');
await p.waitForTimeout(50);
assert.equal((await p.evaluate(() => window.__app.vis()))[4], true, 'Umschalt+Tab blendet nicht ein');
await p.keyboard.press('Tab');
assert.equal((await p.evaluate(() => window.__app.vis()))[4], false, 'Tab blendet nicht aus');
await p.keyboard.press('Control+Shift+H');
assert.deepEqual(await p.evaluate(() => window.__app.vis()), [true, true, true, true, true]);
const mess = await p.evaluate(async () => {
  const app = window.__app, d = app.data();
  const cf = d.uniq[d.inst[3].u].faces.findIndex(f => f.type === 'zylindrisch');
  app.clearSel();
  await app.select({ k: 'face', id: cf, inst: 3 });
  await app.select({ k: 'face', id: cf, inst: 4 }, true);
  return window.__lastMeasure.rows;
});
const loch = mess.find(r => r[0] === 'Lochabstand Mitte–Mitte');
if (!loch || Math.abs(loch[1] - 130) > 1e-4) throw new Error('Lochabstand ' + JSON.stringify(mess));
const text = await p.locator('#mresult').innerText();
if (!text.includes('Bolzen 1 <1>') || !text.includes('Bolzen 1 <2>')) throw new Error('Bauteilname fehlt: ' + text);
await p.evaluate(() => window.__app.verschiebe('Bolzen 1 <2>', 10, 0, 0));
const neu = await p.evaluate(() => window.__lastMeasure.rows.find(r => r[0] === 'Lochabstand Mitte–Mitte')[1]);
if (Math.abs(neu - Math.hypot(130, 50)) > 1e-3) throw new Error('Messung folgt der Lage nicht: ' + neu);
await p.evaluate(() => window.__app.rueckgaengig());
await zeile('Winkelbaugruppe').click();
await p.evaluate(() => window.__app.oeffneBewegen());
await p.evaluate(() => window.__app.act('transp', window.__app.nodes().find(n => n.name === 'Grundplatte')));
await p.evaluate(() => window.__app.fitIso());
await p.waitForTimeout(400);
fs.mkdirSync('docs', { recursive: true });
await p.screenshot({ path: ziel });
if (errs.length) throw new Error(errs.join(' | '));
await b.close();
console.log('OK: Baugruppe', ziel);
await import('./smoke-triade-esc.mjs');
